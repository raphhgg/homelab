#!/usr/bin/env python3
"""
Generate Kometa metadata files from Sonarr tags
Maps Sonarr tags to custom Plex genres for smart filtering
Creates separate metadata file per genre in metadata/tvshows/genre/
"""

import sqlite3
import json
from pathlib import Path
from collections import defaultdict

# Tag ID to custom genre mapping (proper genre names with * suffix to distinguish from Plex native genres)
TAG_TO_GENRE = {
    10: 'Anime *',
    11: 'Cartoons *',
    27: 'Drama *',
    28: 'Horror *',
    30: 'Documentary *',
    32: 'Science Fiction *',
    33: 'Dramedy *',
    34: 'Crime & Mystery *',
    36: 'Conspiracy & Espionage *',
    12: 'True Crime *',
    13: 'Reality *',
    31: 'Sports *',
    37: 'Superheroes *',
    35: 'Supernatural *',
    8: 'Sitcom *',
    38: 'Organized Crime *',
}

# Genre name mapping (for file names)
GENRE_FILE_NAMES = {
    'Anime *': 'anime',
    'Cartoons *': 'cartoons',
    'Drama *': 'drama',
    'Horror *': 'horror',
    'Documentary *': 'documentary',
    'Science Fiction *': 'scifi',
    'Dramedy *': 'dramedy',
    'Crime & Mystery *': 'crime_mystery',
    'Conspiracy & Espionage *': 'conspiracy_espionage',
    'True Crime *': 'true_crime',
    'Reality *': 'reality',
    'Sports *': 'sports',
    'Superheroes *': 'superheroes',
    'Supernatural *': 'supernatural',
    'Sitcom *': 'sitcom',
    'Organized Crime *': 'organized_crime',
}

def write_yaml_manually(file_path, shows_dict, genre_label):
    """Write YAML metadata file manually without PyYAML"""
    with open(file_path, 'w') as f:
        f.write('# Auto-generated from Sonarr tags\n')
        f.write('# Generated by: scripts/generate_kometa_metadata_from_sonarr.py\n')
        f.write(f'# Genre: {genre_label}\n')
        f.write('\n')
        f.write('metadata:\n')

        for title in sorted(shows_dict.keys()):
            # Escape quotes in title
            if '"' in title or "'" in title or ':' in title:
                # Use double quotes and escape internal quotes
                escaped_title = title.replace('\\', '\\\\').replace('"', '\\"')
                f.write(f'  "{escaped_title}":\n')
            else:
                f.write(f'  {title}:\n')

            f.write(f'    genre: {genre_label}\n')

def main():
    # Database paths
    sonarr_db = Path('/volume2/docker/appdata/sonarr/sonarr.db')
    output_dir = Path('/volume2/docker/appdata/kometa/metadata/tvshows/genre')

    # Create output directory
    output_dir.mkdir(parents=True, exist_ok=True)

    # Connect to Sonarr database
    conn = sqlite3.connect(sonarr_db)
    cursor = conn.cursor()

    # Get all series with tags
    cursor.execute("SELECT Title, Tags FROM Series ORDER BY Title")
    series_data = cursor.fetchall()

    # Group shows by genre
    shows_by_genre = defaultdict(dict)
    genre_counts = defaultdict(int)

    for title, tags_json in series_data:
        try:
            tags = json.loads(tags_json)
            if not tags:
                continue

            # Find matching custom genres for this show
            for tag_id in tags:
                if tag_id in TAG_TO_GENRE:
                    genre_label = TAG_TO_GENRE[tag_id]
                    shows_by_genre[genre_label][title] = {'genre': genre_label}
                    genre_counts[genre_label] += 1

        except (json.JSONDecodeError, TypeError):
            continue

    conn.close()

    # Write separate file for each genre
    total_shows = 0
    for genre_label, shows in shows_by_genre.items():
        if not shows:
            continue

        file_name = GENRE_FILE_NAMES[genre_label]
        output_file = output_dir / f'{file_name}.yml'

        write_yaml_manually(output_file, shows, genre_label)

        print(f"✓ Generated {output_file} ({len(shows)} shows)")
        total_shows += len(shows)

    print(f"\n✓ Total: {total_shows} shows across {len(shows_by_genre)} genres")
    print("\nGenre distribution:")
    for genre, count in sorted(genre_counts.items()):
        file_name = GENRE_FILE_NAMES[genre]
        print(f"  {file_name}: {count} shows")

if __name__ == '__main__':
    main()
