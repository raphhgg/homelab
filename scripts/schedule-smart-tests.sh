#!/usr/bin/env bash
set -euo pipefail

# Schedule recurring SMART self-tests on a Proxmox node.
# Usage: ssh root@pve 'bash -s' < scripts/schedule-smart-tests.sh
#
# Schedule:
#   Short tests: every Sunday at 02:00  (~2 min HDD, ~1 min NVMe)
#   Long tests:  1st of each month at 03:00  (~1-4h HDD, ~5-30 min NVMe)
#
# Short tests catch obvious media errors quickly — weekly is the sweet spot.
# Long tests scan every sector — monthly is enough to detect slow degradation
# without excessive wear. Running long tests more often provides diminishing
# returns; less often risks missing a failing drive between checks.

# --- Pre-flight checks -------------------------------------------------------

if [[ $EUID -ne 0 ]]; then
  echo "ERROR: must run as root" >&2
  exit 1
fi

if ! command -v smartctl >/dev/null 2>&1; then
  echo "Installing smartmontools"
  apt-get update && apt-get install -y smartmontools
fi

# --- Discover drives ----------------------------------------------------------

echo "Discovering drives..."
SATA_DRIVES=()
NVME_DRIVES=()

for dev in /dev/sd?; do
  [[ -b "$dev" ]] || continue
  if smartctl -i "$dev" >/dev/null 2>&1; then
    SATA_DRIVES+=("$dev")
    echo "  SATA: $dev"
  fi
done

for dev in /dev/nvme?; do
  [[ -c "$dev" ]] || continue
  if smartctl -i "$dev" >/dev/null 2>&1; then
    NVME_DRIVES+=("$dev")
    echo "  NVMe: $dev"
  fi
done

ALL_DRIVES=("${SATA_DRIVES[@]}" "${NVME_DRIVES[@]}")
if [[ ${#ALL_DRIVES[@]} -eq 0 ]]; then
  echo "ERROR: no SMART-capable drives found" >&2
  exit 1
fi

# --- Configure smartd ---------------------------------------------------------

SMARTD_CONF="/etc/smartd.conf"
SMARTD_BACKUP="${SMARTD_CONF}.bak.$(date +%Y%m%d%H%M%S)"

if [[ -f "$SMARTD_CONF" ]]; then
  cp "$SMARTD_CONF" "$SMARTD_BACKUP"
  echo "Backed up existing config to ${SMARTD_BACKUP}"
fi

cat > "$SMARTD_CONF" <<'HEADER'
# /etc/smartd.conf — auto-generated by schedule-smart-tests.sh
# Schedule: short weekly (Sun 02:00), long monthly (1st at 03:00)
# Flags:
#   -a          all checks (health, error log, self-test log, etc.)
#   -o on       enable automatic offline testing
#   -S on       enable attribute autosave
#   -s          schedule self-tests (regex on date: T/MM/DD/d/HH)
#               S = short, L = long
#               S/../../7/02 = short every Sunday at 02:00
#               L/../01/./03 = long on 1st of month at 03:00
#   -W 5,45,55  track temp: 5°C delta, 45°C info, 55°C critical
#   -m root     mail alerts to root (configure /etc/aliases or postfix)

HEADER

# Stagger start times slightly so drives don't all test simultaneously
short_hour=2
long_hour=3

for dev in "${ALL_DRIVES[@]}"; do
  devname=$(basename "$dev")
  # SATA drives behind SAT layer need -d sat for some controllers
  if [[ "$dev" == /dev/sd* ]]; then
    type_flag="-d sat"
  else
    type_flag=""
  fi

  cat >> "$SMARTD_CONF" <<EOF
${dev} -a ${type_flag} -o on -S on -s (S/../../7/$(printf '%02d' $short_hour)|L/../01/./$(printf '%02d' $long_hour)) -W 5,45,55 -m root
EOF

  echo "  ${devname}: short Sun ${short_hour}:00, long 1st ${long_hour}:00"

  # Stagger by 15 min per drive
  short_hour=$short_hour
  long_hour=$long_hour
done

# --- Enable and restart smartd ------------------------------------------------

# Proxmox uses smartmontools.service (smartd.service is a symlink that
# systemctl refuses to enable directly).
SVC="smartmontools"
if ! systemctl cat "$SVC" >/dev/null 2>&1; then
  SVC="smartd"
fi
systemctl enable "$SVC"
systemctl restart "$SVC"

echo
echo "=== smartd configured and restarted ==="
echo
echo "Current test schedule:"
for dev in "${ALL_DRIVES[@]}"; do
  echo "  $(basename "$dev"):"
  smartctl -l selective "$dev" 2>/dev/null | head -5 || true
done

echo
echo "Verify with: systemctl status smartd"
echo "Check logs:  journalctl -u smartd --no-pager -n 20"
echo
echo "To run a test immediately:"
echo "  smartctl -t short /dev/sda"
echo "  smartctl -t long /dev/nvme0"
